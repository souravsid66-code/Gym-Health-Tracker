"""NumPy array operations and demonstrations."""
import numpy as np
a = np.array([1,2,3,4,5])
print("a[0]:", a[0])
print("a[1]:", a[1])
print("a[2]:", a[2])
print("a[3]:", a[3])
print("a[4]:", a[4])
print(np.__version__)  #if we check numpy version
print(type(a)) #if we check type of a
print(a.dtype) #if we check the data type of a
print(a.ndim) #if we check the number of dimensions of a
